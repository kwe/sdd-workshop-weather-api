#!/usr/bin/env bash
# Regenerate aidlc-docs/features/INDEX.md from each feature's aidlc-state.md.
# Run on main by the orchestrator after merging a feature.
set -euo pipefail

root=$(git rev-parse --show-toplevel)
dir="$root/aidlc-docs/features"
mkdir -p "$dir"
out="$dir/INDEX.md"

{
  echo "# AI-DLC Feature Index"
  echo
  echo "Generated by \`scripts/aidlc-index.sh\`. Do not edit by hand."
  echo
  echo "| Feature | Current Stage | Status | State | Audit |"
  echo "|---|---|---|---|---|"
  for state in "$dir"/*/aidlc-state.md; do
    [ -f "$state" ] || continue
    id=$(basename "$(dirname "$state")")
    stage=$(sed -n 's/^- \*\*Current Stage\*\*: *//p' "$state" | head -1)
    status=$(sed -n 's/^- \*\*Status\*\*: *//p' "$state" | head -1)
    echo "| $id | ${stage:-?} | ${status:-?} | [state]($id/aidlc-state.md) | [audit]($id/audit.md) |"
  done
} > "$out"

echo "Wrote $out"
